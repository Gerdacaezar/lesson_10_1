# Агрегация данных — это процесс обобщения и свертывания данных с целью их анализа,
# упрощения и получения ключевой информации.
# Этот процесс включает различные операции для создания сводных показателей из более детализированных данных.

# Метод agg — позволяет выполнять несколько операций агрегации на различных столбцах DataFrame одновременно.

# Синтаксис:
# DataFrame.agg(func, axis=0, *args, **kwargs)

# Параметры метода:
# func — функция или словарь функций для агрегации.
# Возможные типы func: Один оператор агрегации, например 'mean', 'sum'.

# Список операторов агрегации для применения к каждому столбцу.
# Словарь, где ключи — это имена столбцов, а значения — функции агрегации или список функций для конкретного столбца.
# axis — ось для применения функции агрегации: 0 или 'index' — для строк; 1 или 'columns' — для столбцов.
# *args, **kwargs — дополнительные аргументы, передаваемые в функцию агрегации.

# Примеры использования метода
# Применение одной функции ко всем столбцам:
# df.agg('mean')

# Применение команды на несколько функций ко всем столбцам:
# df.agg(['mean', 'sum'])

# Применение функции к конкретным столбцам:
# df.agg({'column1': 'mean', 'column2': 'sum'})

# Применение нескольких функций к одному и нескольким столбцам:
# df.agg({
#     'column1': ['mean', 'sum'],
#     'column2': ['min', 'max']
# })

# Группировка данных по странам и вычисление средней цены и рейтинга
data = {
    "country": ["FRANCE", "italy", "Spain", "france", "ITALY", "spain"],
    "price": [20, 15, 30, 22, 18, 25],
    "points": [1, 2, 3, 4, 5, 6],
}

df = pd.DataFrame(data)

mean_price_and_rating_by_country = df.groupby("country").agg({"price": "mean", "points": "mean"})
print(mean_price_and_rating_by_country.head())
print("___10")

