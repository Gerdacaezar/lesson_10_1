# Группировка данных

# Метод groupby() — позволяет сгруппировать данные по одному или нескольким столбцам,
# или по результатам какой-либо функции.

# Синтаксис метода:

# DataFrame.groupby(
#     by=None,  # имя столбца или список имен столбцов для группировки, либо функция для группировки.
#     axis=0,  # ось для группировки (по умолчанию axis=0, что означает группировку по строкам).
#     level=None,
#     as_index=True,
#     sort=True,  # сортирует сгруппированные ключи (по умолчанию True).
#     group_keys=True,  # добавляет ключи групп в индекс результирующего объекта (по умолчанию True).
#     squeeze=NoDefault.no_default,
#     observed=False,  # для категориальных данных. Если True, возвращает только группы, которые представлены в данных.
#     dropna=True,  # если True, группы, содержащие NaN-значения, исключаются (по умолчанию True).
# )

# level — уровень для группировки, используется для многомерных индексов.
# Позволяет группировать данные по определенному уровню индекса,
# что полезно для сложных многомерных данных с мультииндексами.

# as_index — определяет, будет ли результирующий объект DataFrame или Series содержать группировочные метки
# (уникальные значения или комбинации значений, которые используются для определения групп при выполнении
# группировки данных в pandas) как индекс.
# Если as_index=True, метки групп будут использоваться в качестве индекса результирующего DataFrame.
# Если False, метки групп будут добавлены как обычные столбцы.

# squeeze — уменьшает размерность результирующего объема данных. Позволяет сжать оси в DataFrame или Series,
# если группировка приводит к объекту с размерностью 1, что может сделать результат более компактным.


# Примеры использования:

# Группировка по одному столбцу:
# df.groupby('column_name')

# Группировка по нескольким столбцам:
# df.groupby(['column1', 'column2'])

# Использование агрегирующих функций:
# df.groupby('column_name').mean()
# df.groupby(['column1', 'column2']).sum()

# Здесь df.groupby('column_name') группирует строки DataFrame df по уникальным значениям в столбце column_name.
# Метод mean() вычисляет среднее значение для всех числовых столбцов в каждой группе. Результат — новый DataFrame,
# где индексом являются уникальные значения из column_name, а значениями — средние значения для каждой группы.

# Группировка с использованием функции:
# df.groupby(lambda x: x // 10 * 10)
# Лямбда-функция берет индекс строки x, делит его на 10 с целочисленным делением (x // 10),
# затем умножает результат на 10 (* 10). Это приводит к округлению индекса до ближайшего меньшего десятка. Например:
# Если x = 5, то 5 // 10 * 10 будет 0.
# Если x = 15, то 15 // 10 * 10 будет 10.
# Если x = 23, то 23 // 10 * 10 будет 20.
# Метод groupby использует лямбда-функцию для определения групп.
# Каждая строка в DataFrame будет отнесена к группе в зависимости от значения ее индекса,
# преобразованного этой функцией.
# Таким образом мы получим:
# Группа с меткой 0 — индексы от 0 до 9.
# Группа с меткой 10 — индексы от 10 до 19.
# Группа с меткой 20 — индексы от 20 до 29, и так далее.

# Пример с несколькими параметрами:
# df.groupby(['column1', 'column2'], as_index=False, sort=False)
# Этот пример демонстрирует, как группировать строки DataFrame df по значениям в двух столбцах (column1 и column2)
# с дополнительными параметрами as_index = False и sort = False.

# Пример
# Рассмотрим пример с группировкой данных и вычислением средней цены:

# Предположим, у нас есть DataFrame df с данными о винах
df = pd.DataFrame(
    {"country": ["France", "Italy", "Spain", "France", "Italy", "Spain"], "price": [20, 15, 30, 22, 18, 25]}
)

# Группировка данных по странам
country_grouped = df.groupby("country")

# Вычисление средней цены для каждой страны
mean_price_by_country = country_grouped["price"].mean()
print(mean_price_by_country)
print("___1")

# Сортировка данных
# Метод sort_values() — используется, чтобы отсортировать данные по цене в порядке убывания.

# Синтаксис метода:
# DataFrame.sort_values(
#    by,  # название столбца или список из нескольких названий столбцов, по которым будет выполняться сортировка.
#    axis=0,  # ось для сортировки (0 или 'index' — для строк; 1 или 'columns' — для столбцов).
#    ascending=True,  # сортировка по возрастанию (по умолчанию True); можно также указать список.
#    inplace=False,  # если True, выполняет операцию сортировки «на месте» и возвращает None, меняя исходный DataFrame.
#    kind='quicksort',  # метод сортировки; по умолчанию 'quicksort'. Варианты: 'mergesort', 'heapsort', 'stable'.
#    na_position='last',  # позиция для NA/NaN-значений: 'first' или 'last'. По умолчанию 'last'.
#    ignore_index=False,  # если True, то после сортировки сбрасывает индексы на дефолтные.
#    key=None,  # функция, которая будет применена к значениям перед сортировкой.
# )

# Подробнее про сортировки:
#       'quicksort' — быстрая сортировка. Обычно используется, когда нужна быстрая сортировка,
# а устойчивость (сохранение относительного порядка равных элементов) не является критичной.
#       'mergesort' — сортировка слиянием. Обычно используется, когда нужна устойчивая сортировка,
# особенно на больших наборах данных.
#       'heapsort' — пирамидальная сортировка. Обычно используется, когда важна производительность
# и минимальное использование памяти, а устойчивость не является важной.
#       'stable' — устойчивая сортировка. Обычно используется,
# когда требуется устойчивая сортировка с хорошей производительностью на большинстве данных.


# Примеры использования метода:

# Сортировка по одному столбцу:
# df.sort_values(by='column_name')

# Сортировка по нескольким столбцам:
# df.sort_values(by=['column1', 'column2'])

# Сортировка по убыванию:
# df.sort_values(by='column_name', ascending=False)

# Сортировка «на месте»:
# df.sort_values(by='column_name', inplace=True)

# Сортировка с использованием определенного метода сортировки:
# df.sort_values(by='column_name', kind='mergesort')
# Этот пример демонстрирует, как отсортировать строки DataFrame по значениям в столбце column_name,
# используя алгоритм сортировки слиянием — mergesort.
#
# Сортировка с размещением NaN-значений в начале:
# df.sort_values(by='column_name', na_position='first')

# Сортировка с применением пользовательской функции:
# df.sort_values(by='column_name', key=lambda x: x.str.lower())


# Примеры

data = {"country": ["France", "Italy", "Spain", "France", "Italy", "Spain"], "price": [20, 15, 30, 22, 18, 25]}

df = pd.DataFrame(data)

# Сортировка по столбцу 'price' в порядке возрастания
sorted_by_price = df.sort_values(by="price")
